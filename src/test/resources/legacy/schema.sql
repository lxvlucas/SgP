-- Fixture do esquema anterior: sem histórico Flyway, com nomes de constraints antigos.
CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255), funcao VARCHAR(255), nome VARCHAR(255), senha VARCHAR(255),
    CONSTRAINT uk_usuario_email_legado UNIQUE (email)
);
CREATE TABLE projeto (
    percentual_conclusao DOUBLE PRECISION, id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255), nome VARCHAR(255)
);
CREATE TABLE tarefa (
    peso_percentual DOUBLE PRECISION, prazo DATE, progresso DOUBLE PRECISION,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projeto_id BIGINT REFERENCES projeto(id), responsavel_id BIGINT REFERENCES usuario(id),
    descricao VARCHAR(255), status VARCHAR(255), titulo VARCHAR(255)
);
CREATE TABLE projeto_colaboradores (
    projeto_id BIGINT NOT NULL REFERENCES projeto(id),
    usuario_id BIGINT NOT NULL REFERENCES usuario(id)
);
