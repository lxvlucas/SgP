-- Estrutura equivalente às entidades existentes antes da adoção do Flyway.
-- Preserva campos opcionais e os valores de status legados.
CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    email VARCHAR(255) UNIQUE,
    senha VARCHAR(255),
    funcao VARCHAR(255)
);

CREATE TABLE projeto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    descricao VARCHAR(255),
    percentual_conclusao DOUBLE PRECISION
);

CREATE TABLE tarefa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255),
    descricao VARCHAR(255),
    prazo DATE,
    peso_percentual DOUBLE PRECISION,
    progresso DOUBLE PRECISION,
    status VARCHAR(255),
    responsavel_id BIGINT REFERENCES usuario(id),
    projeto_id BIGINT REFERENCES projeto(id)
);

CREATE TABLE projeto_colaboradores (
    projeto_id BIGINT NOT NULL REFERENCES projeto(id),
    usuario_id BIGINT NOT NULL REFERENCES usuario(id)
);
